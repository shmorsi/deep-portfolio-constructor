"""Write reports/pension/site_pension.json: every figure the website shows for this study, as the text it shows.

The website (shmorsi.github.io) reads only this file for the pension study, so a number on the site
can always be traced to reports/pension/summary.json, which `python -m dpc.cli pension-run` writes.
"""

from __future__ import annotations

import json
from pathlib import Path

LEARNED, GLIDE, SIXTY, LDI, MATCHED = "Learned policy", "Glide path", "60/40", "Liability-driven 40/60", "Fully matched"


def _pct(x: float, digits: int = 1) -> str:
    return f"{100 * x:.{digits}f}%"


def _signed_pct(x: float, digits: int = 1) -> str:
    return f"{'+' if x > 0 else '−' if x < 0 else ''}{abs(100 * x):.{digits}f}%"


def _cost(x: float) -> str:
    """A cost as dollars per $100 of promises."""
    return f"${100 * x:.1f}"


ORDER = [SIXTY, LDI, MATCHED, GLIDE, LEARNED]


def _stress_rows(stress: dict, horizon: str) -> list[str]:
    names = list(next(iter(stress["shocks"].values()))["horizons"][horizon]["policies"])
    rows = ["| Surprise (+10 bp) | Stocks | 10-year yield | The promise | " + " | ".join(names) + " |", "|---|---:|---:|---:|" + "---:|" * len(names)]
    for sh in stress["shocks"].values():
        r = sh["horizons"][horizon]
        cells = " | ".join(f"{v['points']:+.2f} (±{v['half_width']:.2f})".replace("-", "−") for v in r["policies"].values())
        rows.append(f"| {sh['name']} | {r['stocks_pct']:+.2f}% | {r['yield_bp']:+.1f} bp | {r['promise_pct']:+.2f}% | {cells} |".replace("-", "−").replace("| −−−", "| ---"))
    return rows


def results_markdown(s: dict, anatomy: dict | None = None, stress: dict | None = None) -> str:
    """reports/pension/results.md: every table of the study, generated from summary.json. Do not edit by hand."""
    sim, walk, hist = s["simulated"], s["model_risk"], s["history"]
    c = lambda x: f"${100 * x:.1f}"  # noqa: E731
    sg = lambda x: _signed_pct(x, 1).replace("%", "")  # noqa: E731
    out = ["# Pension Lab: results\n",
           f"Generated by `python -m dpc.cli pension-site` from `reports/pension/summary.json` (commit {s['commit']}). "
           f"Data: {s['data']['months']} months, {s['data']['first_month']} to {s['data']['last_month']}. "
           f"A plan {100 * s['plan']['funded_at_start']:.0f}% funded, {s['plan']['schedule_years']} years of indexed payments "
           f"(duration {s['plan']['liability_duration_at_4pct']:.1f} years at 4%), followed for {s['plan']['horizon_months'] // 12} years. "
           "Costs are what the sponsor pays in plus any shortfall left at the end, per $100 promised, in start-of-plan money. "
           "The score is the average cost plus the average cost of the worst 5%. Do not edit by hand.\n"]

    def block(title: str, b: dict, tail_key: str, tail_name: str) -> None:
        out.append(f"## {title}\n")
        split = "bonds_mean" in b["policies"][ORDER[0]]          # the walk through history records the share in stocks only
        out.append(f"| Policy | Average cost | {tail_name} | Fully funded at year 20 | Average in stocks |" + (" In 10-year bonds | In matching bonds |" if split else ""))
        out.append("|---|---:|---:|---:|---:|" + ("---:|---:|" if split else ""))
        for n in ORDER:
            r = b["policies"][n]
            extra = f" {_pct(r['bonds_mean'], 0)} | {_pct(r['matching_mean'], 0)} |" if split else ""
            out.append(f"| {n} | {c(r['mean_cost'])} | {c(r[tail_key])} | {_pct(r['funded_end_share'], 0)} | {_pct(r['stocks_mean'], 0)} |{extra}")
        out.append("\n| Learned policy minus | Difference | 95% interval | Verdict (pre-registered rule) |")
        out.append("|---|---:|---|---|")
        for n in ORDER[:-1]:
            d = b["learned_minus"][n]
            out.append(f"| {n} | {sg(d['difference'])} | {sg(d['lo'])} to {sg(d['hi'])} | {d['verdict']} |")
        out.append("")

    block(f"Test 1: {sim['scenarios']:,} simulated futures (seed {sim['seed']})", sim, "cvar_cost", "Worst 5%")
    out.append("Differences are in the score (average cost plus worst-5% cost), per $100 promised; below zero favours the learned policy.\n")
    block(f"Test 1b: {walk['scenarios']:,} futures in which the yield has no pull to an average (seed {walk['seed']}), policies not retrained", walk, "cvar_cost", "Worst 5%")
    block(f"Test 2: {hist['starts']} real 20-year periods, starting each December from {hist['first_start'] - 1} to {hist['last_start'] - 1}, walking forward",
          hist, "worst_cost", "Worst period")
    out.append(f"Differences in test 2 are in the average cost, per $100 promised, with start years resampled in blocks of {hist['block_years']}. "
               "The periods overlap: about three are independent.\n")
    g = s["generator"]
    out.append("## The scenario generator and the training\n")
    out.append(f"- Yield: AR(1) with coefficient {g['yield_phi']:.4f} a month around {100 * g['yield_mean']:.2f}%. Inflation: AR(1) with coefficient {g['inflation_phi']:.3f}. "
               f"Shocks are resampled from history in blocks averaging {g['block_months']} months.")
    t = s["training"]
    out.append(f"- {t['networks']} networks of {t['parameters']:,} parameters each ({len(t['seeds'])} seeds for the simulated tests and for each of the walk-forward refits), "
               f"{t['steps']} steps of {t['batch']:,} scenarios, {t['train_scenarios']:,} training and {t['validation_scenarios']:,} validation scenarios per network.\n")
    if anatomy:
        bf = anatomy["by_funded"]
        out.append("## What the learned policy holds (a description made after the test; not pre-registered)\n")
        out.append("Average weights in the test-1 futures, by the funded ratio at each monthly decision, next to the glide path at the same funded ratio.\n")
        out.append("| Funded ratio | Share of months | Glide path: stocks | Learned: stocks | Learned: 10-year bonds | Learned: matching bonds |")
        out.append("|---|---:|---:|---:|---:|---:|")
        for i, name in enumerate(bf["buckets"]):
            if bf["learned"][i] is not None:
                lw = bf["learned"][i]
                out.append(f"| {name} | {_pct(bf['share_of_months'][i], 0)} | {_pct(bf['glide'][i][0], 0)} | {_pct(lw[0], 0)} | {_pct(lw[1], 0)} | {_pct(lw[2], 0)} |")
        by = anatomy["by_yield"]
        out.append(f"\nThe same, by the level of the yield, for plans between {100 * by['funded_between'][0]:.0f}% and {100 * by['funded_between'][1]:.0f}% funded.\n")
        out.append("| Yield | Share of those months | Glide path: stocks | Learned: stocks | Learned: 10-year bonds | Learned: matching bonds |")
        out.append("|---|---:|---:|---:|---:|---:|")
        for i, name in enumerate(by["buckets"]):
            if by["learned"][i] is not None:
                lw = by["learned"][i]
                out.append(f"| {name} | {_pct(by['share_of_months'][i], 0)} | {_pct(by['glide'][i][0], 0)} | {_pct(lw[0], 0)} | {_pct(lw[1], 0)} | {_pct(lw[2], 0)} |")
        out.append("")
        tg = anatomy.get("tuned_glide")
        if tg:
            n = tg["numbers"]
            avg = lambda k: sum(x[k] for x in n) / len(n)  # noqa: E731
            out.append("## A glide path tuned on the same simulations (added after the test; not pre-registered)\n")
            out.append("The protocol's glide path has textbook numbers. Here its four numbers are trained on the same scenarios, by the same method and for the "
                       f"same score as the network ({len(n)} seeds, averaged). Tuned: stocks {_pct(avg('stocks_when_short'), 0)} while the plan is under "
                       f"{_pct(avg('slide_from'), 0)} funded, sliding to {_pct(avg('stocks_when_funded'), 0)} at {_pct(avg('slide_to'), 0)} funded "
                       "(the protocol's: 70% under 80%, sliding to 20% at 110%).\n")
            out.append("| Test | Tuned glide path: average cost | Worst 5% | Fully funded at year 20 | Average in stocks | Learned minus tuned (score) | 95% interval | Reading |")
            out.append("|---|---:|---:|---:|---:|---:|---|---|")
            for key, name in (("simulated", "Test 1 futures"), ("model_risk", "Test 1b futures (no pull to an average)")):
                r, d = tg[key]["policy"], tg[key]["learned_minus_tuned"]
                out.append(f"| {name} | {c(r['mean_cost'])} | {c(r['cvar_cost'])} | {_pct(r['funded_end_share'], 0)} | {_pct(r['stocks_mean'], 0)} | "
                           f"{sg(d['difference'])} | {sg(d['lo'])} to {sg(d['hi'])} | {d['verdict']} |")
            out.append("")
        om = anatomy.get("one_month_blocks")
        if om:
            out.append("## Futures with nothing to recognise (added after the test; not pre-registered)\n")
            out.append("The simulated futures of tests 1 and 1b replay history in runs averaging 12 months, and the network sees the last 12 months. "
                       f"Here the same policies, not retrained, are run on {om['scenarios']:,} futures whose months are drawn one at a time (seed {om['seed']}): "
                       "there is no run of history to recognise.\n")
            out.append("| Policy | Average cost | Worst 5% | Fully funded at year 20 | Average in stocks |")
            out.append("|---|---:|---:|---:|---:|")
            for name, r in om["policies"].items():
                out.append(f"| {name} | {c(r['mean_cost'])} | {c(r['cvar_cost'])} | {_pct(r['funded_end_share'], 0)} | {_pct(r['stocks_mean'], 0)} |")
            out.append("\n| Learned policy minus | Difference (score) | 95% interval | Reading |")
            out.append("|---|---:|---|---|")
            for key, name in (("learned_minus_glide", "Glide path"), ("learned_minus_tuned", "Tuned glide path")):
                d = om[key]
                out.append(f"| {name} | {sg(d['difference'])} | {sg(d['lo'])} to {sg(d['hi'])} | {d['verdict']} |")
            out.append("")
    if stress:
        out.append("## What a Fed surprise does to the plan (World Shock Lab's estimates; not pre-registered)\n")
        out.append(f"World Shock Lab (commit {stress['lab']['lab_commit'][:7]}, `{stress['lab']['source'].split(' ', 1)[1]}`) measures what a 10 bp surprise in US monetary policy does to "
                   f"stocks and to the 10-year yield. Applied to this plan at {100 * stress['at']['funded']:.0f}% funded and a {100 * stress['at']['yield']:.0f}% yield: the move in the "
                   "funded ratio, in points, with a band that adds the two estimates' 90% half-widths (the widest it can be whatever their correlation).\n")
        out.append("On the announcement day:\n")
        out += _stress_rows(stress, "0")
        out.append("\nTwenty trading days later:\n")
        out += _stress_rows(stress, "20")
        out.append("")
    return "\n".join(out) + "\n"


START, END = "<!-- pension:start -->", "<!-- pension:end -->"
READING = {"better": "better than", "worse": "worse than", "no detectable difference": "not detectably different from"}


def readme_section(s: dict, anatomy: dict | None = None, stress: dict | None = None) -> str:
    """The Pension Lab block of README.md, between the pension:start and pension:end markers. Every number comes from summary.json."""
    sim, walk, hist = s["simulated"], s["model_risk"], s["history"]
    P, W, H = sim["policies"], walk["policies"], hist["policies"]
    c = lambda x: f"${100 * x:.1f}"  # noqa: E731
    sg = lambda x: _signed_pct(x, 1).replace("%", "")  # noqa: E731
    v_sim, v_walk, v_hist = (b["learned_minus"][GLIDE]["verdict"] for b in (sim, walk, hist))
    d_sim, d_hist = sim["learned_minus"][GLIDE], hist["learned_minus"][GLIDE]
    if v_sim == "better" and v_hist == "better":
        close = "History agrees with the simulation, on what amounts to about three independent periods."
    elif v_sim == "better":
        close = ("So the saving is a property of the simulated world the policy was trained in. Real history, the test it could not have learned, does not confirm it: "
                 f"there the learned policy is {READING[v_hist]} the glide path.")
    else:
        close = f"The learned policy is {READING[v_sim]} the glide path in simulation and {READING[v_hist]} it on real history."
    out = [START,
           "<!-- Generated by `python -m dpc.cli pension-site` from reports/pension/summary.json. Edit src/dpc/pension/site.py, not this block. -->",
           "",
           f"**The question** ([pre-registered](docs/pension_protocol.md), committed before the test ran): a pension plan is {100 * s['plan']['funded_at_start']:.0f}% funded and has "
           f"promised {s['plan']['schedule_years']} years of inflation-indexed payments. What does keeping that promise cost its sponsor over {s['plan']['horizon_months'] // 12} years "
           "under the policies plans really use, and does a policy trained through a differentiable simulator of the plan cost less than a glide path?",
           "",
           f"**The answer:** In {sim['scenarios']:,} simulated futures the learned policy cost the sponsor **{c(P[LEARNED]['mean_cost'])}** per $100 promised against "
           f"**{c(P[GLIDE]['mean_cost'])}** for the glide path, and {c(P[LEARNED]['cvar_cost'])} against {c(P[GLIDE]['cvar_cost'])} in the worst 5% of futures: "
           f"**{v_sim}** by the pre-registered test (score difference {sg(d_sim['difference'])}, 95% interval {sg(d_sim['lo'])} to {sg(d_sim['hi'])}). "
           f"Over {hist['starts']} real 20-year periods, with every network trained only on data from before its period, it cost **{c(H[LEARNED]['mean_cost'])}** against "
           f"**{c(H[GLIDE]['mean_cost'])}**: **{v_hist}** (difference {sg(d_hist['difference'])}, interval {sg(d_hist['lo'])} to {sg(d_hist['hi'])}). {close}",
           "",
           "![The funded ratio over 20 years under 60/40, the glide path and the learned policy](reports/figures/pension/fans.png)",
           "",
           f"| Policy | Average cost | Worst 5% | Fully funded at year 20 | In stocks | When yields never come back: average, worst 5% | Real history: average, worst period |",
           "|---|---:|---:|---:|---:|---:|---:|"]
