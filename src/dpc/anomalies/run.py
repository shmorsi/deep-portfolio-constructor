"""`python -m dpc.cli anomalies`: write reports/anomalies/ (summary.json, results.md, a figure) and the README block."""

from __future__ import annotations

import json
from pathlib import Path

import numpy as np

from ..logging_utils import get_logger
from . import ZOO, study

log = get_logger(__name__)
LABELS = {"equal_weight": "Equal weight", "factor_momentum": "Factor momentum", "shrinkage_mv": "Shrinkage mean-variance",
          "boosting": "Gradient boosting"}


def _p(x, d=1):
    return f"{100 * x:.{d}f}%"


def _count(n: int, one: str = "clears", many: str = "clear") -> str:
    return f"{n} {one if n == 1 else many}"


def render(root: Path) -> None:
    """Rewrite results.md and the README block from the committed summary.json (no recomputation)."""
    s = json.loads((root / "reports" / "anomalies" / "summary.json").read_text())
    (root / "reports" / "anomalies" / "results.md").write_text(markdown(s))
    update_readme(root, s)


def _clean(o):
    if isinstance(o, dict):
        return {str(k): _clean(v) for k, v in o.items()}
    if isinstance(o, list | tuple):
        return [_clean(v) for v in o]
    if isinstance(o, np.bool_):
        return bool(o)
    if isinstance(o, np.floating | np.integer):
        return o.item()
    if isinstance(o, float) and not np.isfinite(o):
        return None
    return o


def markdown(s: dict) -> str:
    sv, dc, pl, cb = s["survival"], s["decay"], s["pooled"], s["combine"]
    L = ["# The anomaly zoo: results", "",
         "<!-- Generated by `python -m dpc.cli anomalies` from reports/anomalies/summary.json. Do not edit. -->", "",
         f"Fifteen published anomalies as value-weighted top-minus-bottom decile spreads (Kenneth French), {s['start']} to {s['end']} "
         f"({s['months']} months), gross of trading costs. Not pre-registered.", "",
         "## 1. Which survive?", "",
         f"{s['n_t196']} of 15 clear |t| > 1.96, {_count(s['n_t3'])} Harvey, Liu and Zhu's 3.0, and {_count(s['n_bh'], 'survives', 'survive')} a "
         "Benjamini-Hochberg false-discovery rate of 5%. Only momentum is beyond doubt; the rest are within reach of luck in a field that has tested hundreds of signals.", "",
         "| Anomaly | Paper | Return a year | Newey-West t | Sharpe | Before publication | After publication | Decay |",
         "|---|---|---:|---:|---:|---:|---:|---:|"]
    for a in ZOO:
        v, d = sv[a.key], dc[a.key]
        pre = _p(d["pre_ann"]) if d["pre_months"] >= 60 else "(too short)"
        dec = _p(d["decay"], 0) if d["pre_months"] >= 60 and d["decay"] is not None else ""
        L.append(f"| {a.name} | {d['paper']} | {_p(v['mean_ann'])} | {v['t']:.2f} | {v['sharpe']:.2f} | {pre} | {_p(d['post_ann'])} | {dec} |")
    L += ["", "## 2. Did publication kill them?", "",
          f"For the {pl['anomalies_with_pre_sample']} anomalies with at least five years of data before their paper, the average return fell from "
          f"{_p(pl['mean_pre_ann'])} a year before publication to {_p(pl['mean_post_ann'])} after. Pooled with anomaly fixed effects and errors "
          f"clustered by month, the post-publication change is {_p(pl['post_coef_ann'])} a year (t {pl['post_t']:.2f}): an implied decay of "
          f"{_p(pl['implied_decay'], 0)}. McLean and Pontiff (2016) found about 58% across 97 anomalies.", "",
          "## 3. Combining them out of sample", "",
          f"Each month from {s['combine_start']}, using only the past (gradient boosting refitted every January). Long-short weights scaled to sum to one in absolute value.", "",
          "| Strategy | Return a year | t | Volatility | Sharpe | Sharpe since 2000 | Worst fall | Sharpe vs equal weight (90% interval) |",
          "|---|---:|---:|---:|---:|---:|---:|---|"]
    for k, lab in LABELS.items():
        v = cb[k]
        vs = v.get("vs_equal_weight")
        cmp = f"{vs['difference']:+.2f} ({vs['lo90']:+.2f} to {vs['hi90']:+.2f}): {vs['verdict']}" if vs else "the benchmark"
        L.append(f"| {lab} | {_p(v['mean_ann'])} | {v['t']:.2f} | {_p(v['vol_ann'])} | {v['sharpe']:.2f} | {v['sharpe_since_2000']:.2f} | "
                 f"{_p(v['max_drawdown'], 0)} | {cmp} |")
    L += ["", "![Out-of-sample growth of the four ways to hold the zoo](../figures/anomalies/combine.png)", "",
          "## Limits", "",
          "- Decile portfolios, not stocks: no stock-level signal construction, no costs. Short legs of value-weighted deciles are cheaper to trade than equal-weighted ones but not free.",
          "- Publication years are those of the paper usually cited; some anomalies were known earlier in working papers.",
          "- The zoo is fifteen survivors that Kenneth French chose to publish portfolios for, so it is itself a selected set.", ""]
    return "\n".join(L)


def readme_block(s: dict) -> str:
    cb, pl = s["combine"], s["pooled"]
    best = max((k for k in LABELS if k != "equal_weight"), key=lambda k: cb[k]["sharpe"])
    return "\n".join([
        "<!-- anomalies:start -->",
        "<!-- Generated by `python -m dpc.cli anomalies` from reports/anomalies/summary.json. Edit src/dpc/anomalies/run.py, not this block. -->",
        "",
        f"Fifteen published equity anomalies (size, value, profitability, investment, momentum, reversals, accruals, low beta, issuance, low volatility, "
        f"yields) as value-weighted decile spreads, {s['start']} to {s['end']} ([`src/dpc/anomalies/`](src/dpc/anomalies/), "
        "[`reports/anomalies/results.md`](reports/anomalies/results.md)).",
        "",
        f"* **Survival:** {s['n_t196']} of 15 clear |t| > 1.96; {_count(s['n_t3'])} the 3.0 hurdle for a field that has tested hundreds of signals, and "
        f"{_count(s['n_bh'], 'survives', 'survive')} a 5% false-discovery rate.",
        f"* **Publication decay:** returns fell from {_p(pl['mean_pre_ann'])} to {_p(pl['mean_post_ann'])} a year after the papers appeared "
        f"(pooled change {_p(pl['post_coef_ann'])}, t {pl['post_t']:.2f}; implied decay {_p(pl['implied_decay'], 0)}).",
        f"* **Combining out of sample** (from {s['combine_start']}): equal weight Sharpe {cb['equal_weight']['sharpe']:.2f}; the best alternative, "
        f"{LABELS[best].lower()}, {cb[best]['sharpe']:.2f} ({cb[best]['vs_equal_weight']['verdict']} by a block bootstrap).",
        "<!-- anomalies:end -->",
    ])


def update_readme(root: Path, s: dict) -> None:
    readme = root / "README.md"
    text = readme.read_text()
    block = readme_block(s)
    a, b = "<!-- anomalies:start -->", "<!-- anomalies:end -->"
    if a in text:
        text = text[:text.index(a)] + block + text[text.index(b) + len(b):]
    else:
        text = text.replace("## Derivatives and rates", "## The anomaly zoo: what survives, what decays, what combines\n\n" + block + "\n\n## Derivatives and rates", 1)
    readme.write_text(text)


def figure(C, out: Path) -> None:
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    out.mkdir(parents=True, exist_ok=True)
    fig, ax = plt.subplots(figsize=(8, 3.8))
    for k, col in zip(LABELS, ("#1f4e79", "#b5651d", "#6b8e23", "#7b4f9d"), strict=True):
        ax.plot(C.index, (1 + C[k]).cumprod(), label=LABELS[k], color=col)
    ax.set_yscale("log")
    ax.legend(frameon=False, fontsize=8)
    ax.set_title("$1 in each way of holding the zoo, out of sample (log scale)")
    fig.tight_layout()
    fig.savefig(out / "combine.png", dpi=150)
    plt.close(fig)


def main(cfg, refresh: bool = False) -> int:
    R = study.spreads(cfg.paths.data_raw / "anomalies", refresh)
    sv = study.survival(R)
    dc, pooled = study.decay(R)
    log.info("Combining out of sample (gradient boosting refits every January)")
    C = study.combine(R)
    s = {"start": f"{R.index[0]:%Y-%m}", "end": f"{R.index[-1]:%Y-%m}", "months": len(R),
         "n_t196": int((sv["t"].abs() > 1.96).sum()), "n_t3": int((sv["t"].abs() > 3).sum()), "n_bh": int(sv["bh_5pct"].sum()),
         "survival": sv.to_dict(orient="index"), "decay": dc.to_dict(orient="index"), "pooled": pooled,
         "combine_start": f"{C.index[0]:%Y-%m}", "combine": study.summarise(C)}
    s = _clean(s)
    out = cfg.paths.reports / "anomalies"
    out.mkdir(parents=True, exist_ok=True)
    (out / "summary.json").write_text(json.dumps(s, indent=1))
    (out / "results.md").write_text(markdown(s))
    figure(C, cfg.paths.figures / "anomalies")
    update_readme(cfg.root, s)
    log.info("Wrote %s", out)
    return 0
